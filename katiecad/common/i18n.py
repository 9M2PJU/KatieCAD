def tr(schluessel, **kwargs):
    text = TEXTE.get(SPRACHE["aktuell"], {}).get(schluessel)
    if text is None:
        text = TEXTE["de"].get(schluessel, schluessel)
    if kwargs:
        try:
            text = text.format(**kwargs)
        except Exception:
            pass
    return text


def setze_sprache(code):
    if code in TEXTE:
        SPRACHE["aktuell"] = code
