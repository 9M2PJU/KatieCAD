_NACH_NR = {n: (name, h) for n, name, h in RAL_CLASSIC}


def ral_suchen(text):
    """'RAL 5015', 'ral5015', '5015' -> (number, name, hex) or None."""
    t = "".join(ch for ch in str(text) if ch.isalnum()).lower()
    if t.startswith("ral"):
        t = t[3:]
    if not t.isdigit() or int(t) not in _NACH_NR:
        return None
    n = int(t)
    return n, _NACH_NR[n][0], _NACH_NR[n][1]


def _rgb(h):
    h = h.lstrip("#")
    return int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16)


def naechstes_ral(farbe):
    """RAL colour closest to '#rrggbb' -> (number, name, hex, exact?)."""
    try:
        r, g, b = _rgb(farbe)
    except (ValueError, IndexError):
        return None
    best, bd = None, None
    for n, name, h in RAL_CLASSIC:
        r2, g2, b2 = _rgb(h)
        d = (r - r2) ** 2 + (g - g2) ** 2 + (b - b2) ** 2
        if bd is None or d < bd:
            best, bd = (n, name, h), d
    return best[0], best[1], best[2], bd == 0


def familie(nummer):
    return [x for x in RAL_CLASSIC if x[0] // 1000 == nummer]
