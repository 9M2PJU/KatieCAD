_PUNKTE = {"Ä": ("A", [(1, 7), (1, 7.4)], [(3, 7), (3, 7.4)]),
           "Ö": ("O", [(1, 7), (1, 7.4)], [(3, 7), (3, 7.4)]),
           "Ü": ("U", [(1, 7), (1, 7.4)], [(3, 7), (3, 7.4)])}
BREITE = 4.0
SCHRITT = 6.0
KAPPE = 6.0
ZEILE = 10.0                      # line pitch in glyph units


def _glyphen(c):
    c = c.upper() if c != "ß" else "SS"
    out = []
    for ch in c:
        if ch in _A:
            out.append(_A[ch])
        elif ch in _PUNKTE:
            b, p1, p2 = _PUNKTE[ch]
            out.append(_A[b] + [p1, p2])
        elif ch == " ":
            out.append([])
        else:
            out.append([])
    return out


def text_zuege(inhalt, hoehe):
    """Polylines [[(x, y), ...]] of `inhalt` (may contain newlines), lower left corner of
    the first line at (0, 0); `hoehe` = capital height in the plane's units."""
    f = hoehe / KAPPE
    zuege = []
    for zi, zeile in enumerate((inhalt or "").split("\n")):
        x0 = 0.0
        y0 = -zi * ZEILE * f
        for ch in zeile:
            for gl in _glyphen(ch):
                for zug in gl:
                    zuege.append([(x0 + px * f, y0 + py * f) for (px, py) in zug])
                x0 += SCHRITT * f
    return zuege


def text_breite(inhalt, hoehe):
    f = hoehe / KAPPE
    zeilen = (inhalt or "").split("\n")
    n = 0
    for z in zeilen:
        n = max(n, sum(2 if ch == "ß" else 1 for ch in z))
    return max(0.0, n * SCHRITT - (SCHRITT - BREITE)) * f
