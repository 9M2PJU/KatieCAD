"""AutoCAD Color Index (ACI) 1..255 -> sRGB.

The standard table is generated by rule instead of being copied: 1-9 are the basic
colours, 10-249 are 24 hues (15 degree steps) x 10 shades, 250-255 are greys."""
import colorsys

_BASIS = {1: "#ff0000", 2: "#ffff00", 3: "#00ff00", 4: "#00ffff", 5: "#0000ff", 6: "#ff00ff",
          7: "#ffffff", 8: "#808080", 9: "#c0c0c0"}
_GRAU = {250: "#333333", 251: "#505050", 252: "#696969", 253: "#828282", 254: "#bebebe",
         255: "#ffffff"}
# per shade 0..9: (saturation, value)
_STUFEN = ((1.0, 1.0), (0.5, 1.0), (1.0, 0.8), (0.5, 0.8), (1.0, 0.6), (0.5, 0.6),
           (1.0, 0.5), (0.5, 0.5), (1.0, 0.3), (0.5, 0.3))


def _hex(r, g, b):
    return "#%02x%02x%02x" % tuple(int(c * 255 + 1e-6) for c in (r, g, b))


def _bauen():
    t = {0: "#000000"}
    t.update(_BASIS)
    for i in range(10, 250):
        h, k = divmod(i - 10, 10)
        s, v = _STUFEN[k]
        t[i] = _hex(*colorsys.hsv_to_rgb(h * 15 / 360.0, s, v))
    t.update(_GRAU)
    return t


ACI_TABELLE = _bauen()


def aci_hex(nr):
    """ACI 1..255 -> '#rrggbb' or None."""
    try:
        nr = int(nr)
    except (TypeError, ValueError):
        return None
    return ACI_TABELLE.get(nr) if 1 <= nr <= 255 else None


def naechstes_aci(farbe):
    """-> (nr, hex, exact?) of the most similar ACI (1..255)."""
    f = str(farbe).lower()
    try:
        r, g, b = (int(f[k:k + 2], 16) for k in (1, 3, 5))
    except ValueError:
        return None
    bester = None
    for nr in range(1, 256):
        h = ACI_TABELLE[nr]
        d = sum((int(h[k:k + 2], 16) - c) ** 2 for k, c in zip((1, 3, 5), (r, g, b)))
        if bester is None or d < bester[0]:
            bester = (d, nr, h)
    return bester[1], bester[2], bester[0] == 0
